async function main() {
  const fullDoc = buildFullDoc();
  const qDoc = buildQuestionsDoc();
  const solDoc = buildSolutionsDoc();

  const fullBuf = await Packer.toBuffer(fullDoc);
  const qBuf = await Packer.toBuffer(qDoc);
  const solBuf = await Packer.toBuffer(solDoc);

  const fullPath = path.resolve('Экзамен_по_физике_для_преподавателей_Полный.docx');
  const qPath = path.resolve('Экзамен_по_физике_Задания.docx');
  const solPath = path.resolve('Экзамен_по_физике_Ключи_и_Решения.docx');

  fs.writeFileSync(fullPath, fullBuf);
  fs.writeFileSync(qPath, qBuf);
  fs.writeFileSync(solPath, solBuf);

  console.log('Successfully re-generated:');
  console.log('1.', fullPath, `(${fullBuf.length} bytes)`);
  console.log('2.', qPath, `(${qBuf.length} bytes)`);
  console.log('3.', solPath, `(${solBuf.length} bytes)`);
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
