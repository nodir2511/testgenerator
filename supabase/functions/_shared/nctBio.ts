/**
 * Раздел темы по порядку главы и темы банка биологии (главы = уровни курса, темы = параграфы):
 * гл. 1 (13 тем: клетка … онтогенез) и гл. 2 темы 1–7 (генетика … эволюция) — общая биология; гл. 2 темы 8–10 (экология, сообщества, биосфера) — экология;
 * гл. 3 (21 тема) — анатомия человека; гл. 4 темы 1–2 (вирусы, бактерии) — ботаника, темы 3–20 (простейшие … млекопитающие) — зоология;
 * гл. 5 (16 тем: грибы, лишайники, растения) — ботаника. Главы 6+ и темы вне этих границ в режим не берутся.
 */
const BIO_TOPICS_IN_CHAPTER: Record<number, number> = { 1: 13, 2: 10, 3: 21, 4: 20, 5: 16 };

export function bioTopicSection(chapterOrder: number, topicOrder: number): 'gen' | 'bot' | 'zoo' | 'anat' | 'eco' | null {
  const size = BIO_TOPICS_IN_CHAPTER[chapterOrder];
  if (!size || !Number.isFinite(topicOrder) || topicOrder < 1 || topicOrder > size) return null;
  switch (chapterOrder) {
    case 1: return 'gen';
    case 2: return topicOrder <= 7 ? 'gen' : 'eco';
    case 3: return 'anat';
    case 4: return topicOrder <= 2 ? 'bot' : 'zoo';
    default: return 'bot';
  }
}

