function vData() {
  const D = secIdx().map((i) => [CS[i], ST[i]]).filter(([C, s]) => s.out);
  D.forEach(([C, s]) => {
    if (!s.rate) s.rate = rate(C, s, s.out);
  });
  if (!D.length) return null;
  const n = D.length, sev3 = D.filter(([C, s]) => s.out.sev >= 3).length, clean = D.filter(([C, s]) => !s.out.I.length).length;
  const dxAll = D.reduce((a, [C, s]) => a + C.dx.length, 0), dxOk = D.reduce((a, [C, s]) => a + C.dx.filter((r, i) => s.dx[i] === r[2]).length, 0);
  const avg = D.reduce((a, [C, s]) => a + s.rate.st, 0) / n, fin = Math.max(1, Math.min(5, Math.round(avg - 0.4 * sev3)));
  const V = {
    5: ["Золотой врач", "К такому записываются за месяц. Спрашивает, проверяет, не пропускает опасное."],
    4: ["Хороший врач", "Лечит грамотно, есть над чем поработать. Пациенты в основном довольны."],
    3: ["Средний врач", "Где-то попадает точно, где-то промахивается. Пациентам остаётся надеяться."],
    2: ["Слабый врач", "Слишком часто ошибается в диагнозе или назначениях. Пока лучше лечиться у других."],
    1: ["Тупой врач", "Пациенты уходят с осложнениями. Нужно перечитать разбор приёма и пройти заново."]
  }[fin];
  const best = D.slice().sort((a, b) => b[1].rate.st - a[1].rate.st || b[1].pts - a[1].pts)[0], worst = D.slice().sort((a, b) => a[1].rate.st - b[1].rate.st || a[1].pts - b[1].pts)[0];
  const cell = sev3 >= 3, court = sev3 === 0 ? ["⚖️ Суд: оправдан", "Ошибок с тяжёлыми последствиями нет. Врачу объявлена благодарность."] : sev3 === 1 ? ["⚖️ Суд: выговор и штраф", "Одно тяжёлое осложнение. Условно, но под наблюдением."] : sev3 === 2 ? ["⚖️ Суд: лишён лицензии", "Два тяжёлых исхода. Практиковать нельзя, ждёте апелляцию."] : ["🔒 Суд: тюрьма на " + Math.min(10, sev3 * 2) + " лет", "Слишком много пострадавших пациентов. Приговор вынесен."];
  return { D, n, sev3, clean, dxAll, dxOk, fin, V, best, worst, cell, court };
}
