function bind(C, s) {
  const M = $("cxMain"), on = (id, f) => {
    const b = $(id);
    if (b) b.onclick = f;
  };
  on("cxNext", () => {
    if (s.ph === 2 && C.events.some((e) => !s.fired.includes(e.id))) {
      checkEv(C, s, true);
      render();
      return;
    }
    s.ph++;
    s.pain = null;
    render();
  });
  on("evOk", () => {
    s.ev = null;
    s.fb = null;
    checkEv(C, s, false);
    render();
  });
  M.querySelectorAll("[data-ev]").forEach((b) => b.onclick = () => {
    if (s.ev && !s.fb) chooseEv(C, s, +b.dataset.ev);
  });
  on("cxGo", () => {
    const L = secIdx(), n = L.length, p0 = L.indexOf(cur), nx = [...Array(n).keys()].map((k) => L[(p0 + k + 1) % n]).find((i) => !cxDone(i));
    if (nx == null) finished = true;
    else cur = nx;
    render();
    window.scrollTo({ top: 0, behavior: "smooth" });
  });
  on("cxReplay", () => replay(cur));
  on("cxEnd", () => {
    const b = $("cxEnd"), p = b ? pt(b) : [innerWidth / 2, innerHeight / 2];
    s.ph = 5;
    if (s.hard) {
      s.pts *= 2;
      fly("💀 ×2 → " + s.pts, p).style.color = s.pts >= 0 ? "var(--good)" : "var(--bad)";
    }
    const nb = recordAttempt(C, s);
    s.newB = nb.map((b2) => b2[1] + " " + b2[2]);
    if (nb.length) say("🏅 Новое достижение", nb.map((b2) => b2[2]).join(", "));
    updAch();
    render();
    window.scrollTo({ top: 0, behavior: "smooth" });
  });
  M.querySelectorAll("[data-i]").forEach((b) => b.onclick = () => {
    const i = +b.dataset.i;
    if (s.asked.includes(i) || s.asked.length >= C.askLimit) return;
    const p = pt(b);
    const lt = C.late && s.t >= C.late.at ? C.late.ans[C.ask[i][3]] : null;
    if (lt) s.ans[i] = fill(lt, C, s);
    s.asked.push(i);
    s.say = ansOf(C, s, i);
    tick(TMIN.ask, C, s);
    if (C.ask[i][2]) addPts(PTS.ok, p);
    else if (!s.hard) say("Не помогло", "Для диагноза ответ ничего не дал.");
    render();
  });
  M.querySelectorAll("[data-z]").forEach((el) => el.onclick = () => {
    const z = el.dataset.z;
    if (s.exam.includes(z) || s.exam.length >= C.examLimit) return;
    const p = pt(el);
    s.ex[z] = fill(C.exam[z][0], C, s);
    s.exam.push(z);
    tick(TMIN.exam, C, s);
    say(ZONES[z][0], s.ex[z]);
    if (C.exam[z][1]) addPts(PTS.ok, p);
    if (isPain(s.ex[z])) {
      const tok = { z, txt: ["Ай!", "Ой, больно!", "Ай-ай!", "Ой!"][Math.floor(Math.random() * 4)] };
      s.pain = tok;
      setTimeout(() => {
        if (s.pain === tok) {
          s.pain = null;
          if (CS[cur] === C && s.ph === 1) render();
        }
      }, 1500);
    } else s.pain = null;
    render();
  });
  M.querySelectorAll("[data-t]").forEach((b) => b.onclick = () => {
    const id = b.dataset.t, T = TESTS.find((x2) => x2[0] === id);
    if (s.tests.includes(id) || T[2] > C.budget - spent(s)) return;
    const p = pt(b);
    tick(T[3], C, s);
    s.tx[id] = fill(C.tests[id][0], C, s);
    s.tests.push(id);
    const x = C.tests[id];
    say(T[1], s.tx[id] + (s.hard ? "" : ". " + x[2]));
    if (x[1] === 1) addPts(PTS.ok, p);
    else if (x[1] < 0) addPts(PTS.err, p);
    render();
  });
  M.querySelectorAll("[data-r]").forEach((b) => b.onclick = () => {
    if (s.dxDone) return;
    s.dx[+b.dataset.r] = +b.dataset.j;
    render();
  });
  on("cxDx", () => {
    if (C.dx.some((_, r) => s.dx[r] == null)) return;
    const p = pt($("cxDx"));
    s.dxDone = true;
    tick(TMIN.dx, C, s);
    let plus = 0, minus = 0;
    C.dx.forEach(([, , ok], r) => {
      if (s.dx[r] === ok) plus += PTS.ok;
      else minus += PTS.err;
    });
    addPts(plus, [p[0], p[1] - 60]);
    if (minus) setTimeout(() => addPts(minus, p), 300);
    if (s.hard) say("Диагноз записан", "Верен ли он — узнаете в конце.");
    else say(minus ? "Диагноз с ошибками" : "Диагноз верный!", minus ? "Правильные части подсвечены зелёным." : "Переходите к лечению.");
    render();
  });
  M.querySelectorAll("[data-x]").forEach((b) => b.onclick = () => {
    if (s.rxDone) return;
    const i = +b.dataset.x;
    s.rx.includes(i) ? s.rx.splice(s.rx.indexOf(i), 1) : s.rx.push(i);
    render();
  });
  on("cxRx", () => {
    if (!s.rx.length) return;
    const p = pt($("cxRx"));
    s.rxDone = true;
    let plus = 0, minus = 0;
    s.rx.forEach((i) => {
      if (C.rx[i][1] === 1) plus += PTS.ok;
      else minus += PTS.err;
    });
    const missed = C.rx.filter((r, i) => r[1] === 1 && !s.rx.includes(i)).length;
    s.out = outcome(C, s);
    addPts(plus, [p[0], p[1] - 60]);
    if (minus) setTimeout(() => addPts(minus, p), 300);
    if (s.hard) say("Назначения подписаны", "Нажмите «Что было дальше».");
    else say(minus || missed ? "Назначения проверены" : "Идеальный лист назначений!", (minus ? "Красным — ошибочные. " : "") + (missed ? "Пунктиром — забытые. " : "") + "Нажмите «Что было дальше».");
    render();
  });
}
