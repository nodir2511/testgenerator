function wrapText(x, t, mw) {
  const w = t.split(" "), L = [];
  let l = "";
  w.forEach((s) => {
    const q = l ? l + " " + s : s;
    if (x.measureText(q).width > mw && l) {
      L.push(l);
      l = s;
    } else l = q;
  });
  if (l) L.push(l);
  return L;
}
